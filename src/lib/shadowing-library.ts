import type { ScriptItem, TargetCollocation } from "./master-script";

/**
 * Built-in shadowing library: original model answers (not copied from any
 * published book) on themes that recur in Cambridge IELTS Speaking tests
 * (Parts 1, 2 and 3). The themes mirror CAMBRIDGE_TEST_MODULES so the questions
 * match the style learners will meet in the exam.
 *
 * Scripts are written as spoken British English: contractions, discourse
 * markers and short breath-groups, so they suit shadowing rather than reading.
 */

interface LibrarySeed {
  id: string;
  part: 1 | 2 | 3;
  topic: string;
  category: ScriptItem["category"];
  title: string;
  question: string;
  /** Breath-groups, without the trailing "|" (added automatically). */
  chunks: string[];
  stressedWords: string[];
  targetCollocations: TargetCollocation[];
  masterCadenceWpm?: number;
}

function build(seed: LibrarySeed): ScriptItem {
  return {
    id: seed.id,
    part: seed.part,
    topic: seed.topic,
    category: seed.category,
    title: seed.title,
    question: seed.question,
    originalRawSpoken: "",
    upgradedScript: seed.chunks.join(" "),
    thoughtChunks: seed.chunks.map((c) => `${c} |`),
    stressedWords: seed.stressedWords,
    targetCollocations: seed.targetCollocations,
    masterCadenceWpm: seed.masterCadenceWpm ?? 135,
  };
}

